export type SpellingKingdomId =
  | 'nomen'
  | 'doppel'
  | 'ie_h'
  | 'auslaut'
  | 'verwandt'
  | 'merk'
  | 's_laute'
  | 'satz';

export type SpellingTaskKind = 'gap' | 'detective' | 'case_duel' | 'root' | 'dictation';

export interface SpellingKingdomMeta {
  id: SpellingKingdomId;
  title: string;
  shortTitle: string;
  subtitle: string;
  emoji: string;
  color: string;
  crownTarget: number; // Anzahl gemeisterter Aufgaben für die Königreichs-Krone
}

export interface SpellingTask {
  id: string;
  kingdom: SpellingKingdomId;
  /** Das korrekte Zielwort (bzw. Satzzeichen / Satz für Diktat). */
  word: string;
  /** Kurzer, kindgerechter Beispielsatz (wird im Diktat optional vorgelesen / angezeigt). */
  sentence?: string;
  /** 1-Satz-Merkregel (3. Klasse) nach der Antwort. */
  rule: string;
  /** Lücken-Aufgabe (z. B. "H u n ___" → "d"). */
  gap?: {
    before: string;
    after: string;
    answer: string;
    choices: string[];
  };
  /** Fehler-Detektiv: 3 typische Falschschreibungen (plus `word` = 4 Optionen). */
  detectiveWrong?: string[];
  /** Groß-oder-Klein-Duell im Satz. */
  caseDuel?: {
    sentenceBefore: string;
    sentenceAfter: string;
    correct: string;
    wrong: string;
  };
  /** Stammwort- / Verlängerungs-Rätsel. */
  rootQuiz?: {
    question: string;
    answer: string;
    wrong: string[];
  };
  /** Ob sich das Item fürs freie Eintipp-Diktat mit Vorlesestimme eignet (Standard: true außer reine Satzzeichen). */
  allowDictation?: boolean;
}

